# The repo is per-host: launch-polybar.sh starts the bars for $(hostname).
set_machine_name() {
  local cur; cur="$(cat /etc/hostname 2>/dev/null || uname -n)"; cur="${cur%%.*}"
  [[ $cur == "$PROFILE" ]] && return 0
  if ! ((SET_HOSTNAME)); then
    warn "hostname is '${cur}', not '${PROFILE}': ~/utils/launch-polybar.sh starts no bar (run: sudo hostnamectl hostname ${PROFILE})"
    return 0
  fi
  have sudo || { warn "sudo missing - hostname left as '${cur}' (polybar picks its bars by hostname)"; return 0; }
  printf '%s\n' "$cur" > "${BACKUP_DIR}/hostname.before"
  if have hostnamectl && sudo hostnamectl hostname "$PROFILE" 2>/dev/null; then :
  elif printf '%s\n' "$PROFILE" | sudo tee /etc/hostname >/dev/null && sudo hostname "$PROFILE" 2>/dev/null; then :
  else warn "could not set the hostname to ${PROFILE}"; return 0; fi
  ok "hostname: ${cur} -> ${PROFILE} (polybar picks its bars by hostname; old name saved in the backup)"
}

set_session() {
  # Display managers do not read ~/.xinitrc; ~/.xprofile gets the same startup
  # programs (everything before the window manager part of the repo's .xinitrc).
  local xi="${HOME}/.xinitrc"
  if [[ -f $xi ]]; then
    {
      echo "# Written by dots.sh from ~/.xinitrc - used when you log in through a display manager"
      sed '/^## WINDOW MANAGER/,$d' "$xi"
    } > "${HOME}/.xprofile"
  fi
  printf '[Desktop]\nSession=i3\n' > "${HOME}/.dmrc"
  if have sudo && [[ -d /var/lib/AccountsService/users ]]; then
    printf '[User]\nXSession=i3\nSession=i3\nSystemAccount=false\n' \
      | sudo tee "/var/lib/AccountsService/users/${USER}" >/dev/null 2>&1 || true
  fi
  if have sudo && [[ -f /var/lib/sddm/state.conf ]]; then
    sudo sed -i -E 's|^Session=.*|Session=/usr/share/xsessions/i3.desktop|' /var/lib/sddm/state.conf 2>/dev/null || true
  fi
  ok "i3 is the default session (the repo's ~/.zprofile runs startx on tty1)"
}

set_shell() {
  have zsh || { warn "zsh not installed - login shell unchanged"; return 0; }
  local zsh_path current
  zsh_path="$(command -v zsh)"
  current="$(getent passwd "$USER" | cut -d: -f7)"
  [[ $current == */zsh ]] && return 0
  log "Changing the login shell to zsh..."
  grep -qx "$zsh_path" /etc/shells 2>/dev/null || printf '%s\n' "$zsh_path" | sudo tee -a /etc/shells >/dev/null
  sudo chsh -s "$zsh_path" "$USER" || warn "chsh failed - run: chsh -s ${zsh_path}"
}

# Without a running user manager (installer chroot): make the same
# WantedBy= link that 'systemctl --user enable' would make.
enable_user_unit_offline() {
  local unit=$1 dir="${HOME}/.config/systemd/user" f target
  f="$dir/$unit"; [[ -f $f ]] || f="/usr/lib/systemd/user/$unit"
  [[ -f $f ]] || return 1
  target="$(sed -nE 's/^WantedBy=([^[:space:]]+).*/\1/p' "$f" | head -n 1)"
  [[ -n $target ]] || return 1
  mkdir -p "$dir/$target.wants"
  ln -sfn "$f" "$dir/$target.wants/$unit"
}

enable_services() {
  local unit
  etc_exclude "conf/systemd/.config/systemd/user/*.wants/"
  if have systemctl && [[ -n $USER_SERVICES ]]; then
    log "Enabling user services: ${USER_SERVICES}"
    systemctl --user daemon-reload 2>/dev/null || true
    for unit in $USER_SERVICES; do
      if systemctl --user enable --now "$unit" >/dev/null 2>&1; then ok "enabled ${unit}"
      elif systemctl --user enable "$unit" >/dev/null 2>&1; then info "enabled ${unit} (starts at your next login)"
      elif enable_user_unit_offline "$unit"; then info "enabled ${unit} (starts at your next login)"
      else warn "could not enable user unit ${unit}"; fi
    done
  fi
  if [[ -n $SYSTEM_SERVICES ]] && have sudo; then
    for unit in $SYSTEM_SERVICES; do
      sudo systemctl enable --now "${unit%.service}.service" >/dev/null 2>&1 \
        && ok "enabled ${unit}" || warn "could not enable system unit ${unit}"
    done
  fi
}

# The profile names its monitors (i3 workspaces, polybar, ~/.screenlayout).
check_monitors() {
  local vars="${ETC_DIR}/local/${PROFILE}/variables.mk" want m
  [[ -n ${DISPLAY:-} ]] && have xrandr || return 0
  local connected; connected=" $(xrandr --query 2>/dev/null | awk '/ connected/ {printf "%s ", $1}')"
  [[ -n ${connected// /} ]] || return 0
  want="$(sed -nE 's/^[a-z]+_monitor[[:space:]]*=[[:space:]]*"?([^"]+)"?.*/\1/p' "$vars")"
  local -a missing=()
  for m in $want; do [[ $connected == *" $m "* ]] || missing+=("$m"); done
  [[ -x $DOTS_SHARE/monitors.sh ]] && return 0      # mapped at login by monitors.sh
  ((${#missing[@]})) && warn "profile ${PROFILE} is made for outputs ${want//$'\n'/ }, but this machine has${connected}- ${missing[*]} not found. Edit ~/etc/local/${PROFILE}/variables.mk and .screenlayout/main.sh to your outputs, then re-run with --configs-only"
  return 0
}

