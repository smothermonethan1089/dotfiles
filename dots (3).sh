}

# archey3 (in pacman_packages.txt; the pink logo in clean.jpg) no longer runs on
# current Python. If there is no working one, ~/bin/archey3 is a bash port.
archey3_port() {
  local f="${HOME}/bin/archey3" real
  real="$(type -aP archey3 2>/dev/null | grep -vxF "$f" | head -n 1)"
  if [[ -n $real ]] && timeout 10 "$real" >/dev/null 2>&1; then
    [[ -f $f ]] && grep -q 'dots.sh port' "$f" && rm -f "$f"
    return 0
  fi
  cat > "$f" <<'ARCHEY_EOF'
#!/usr/bin/env bash
# archey3 (dots.sh port) - the pink Arch logo + system info from clean.jpg
# A faithful bash port of archey3 (color = magenta, the default module list),
# so it prints the exact same thing without the unmaintained archey3 package.
#   Delete this file to use a real archey3 again.

c1=$'\e[1;35m'   # archey3 color(1): bold magenta  -> bright pink (#FF5C8F)
c2=$'\e[0;35m'   # archey3 color(2): magenta       -> pink (#E02C6D)
cl=$'\e[0m'

color_me() {  # color_me <percent> <low> <medium> <text>  (archey3's thresholds)
  local p=$1 low=$2 med=$3 text=$4 c
  if   (( p <= low )); then c=$'\e[1;32m'
  elif (( p <= med )); then c=$'\e[1;33m'
  else                      c=$'\e[1;31m'; fi
  printf '%s%s%s' "$c" "$text" "$cl"
}
item() { printf '%s%s:%s %s' "$c1" "$1" "$cl" "$2"; }
frac() { printf '%s%s%s/%s' $'\e[0;35m' "$1" "$cl" "$2"; }   # archey3 wraps the numerator

procs="$(ps -u "$(id -un)" -o comm= 2>/dev/null)"
has_proc() { grep -qxE "$1" <<<"$procs"; }

# --- modules: distro, uname n, uname r, uptime, wm, de, packages, ram, cpu, env(editor), fs(/), mpd(albums)
r=()
if [[ -e /etc/pacman.conf ]]; then os="Arch Linux"; else os="$(uname -o)"; fi
