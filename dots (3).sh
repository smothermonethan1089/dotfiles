  mkdir -p "${ETC_DIR}/build"
  (
    cd "${ETC_DIR}/build" && rm -rf yay-bin &&
    git clone --depth 1 https://aur.archlinux.org/yay-bin.git &&
    cd yay-bin && makepkg -si --noconfirm --needed
