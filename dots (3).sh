# 2017 configs on today's versions: syntax-level fixes only, same look.
# Idempotent; lands as one commit in ~/etc so it can be reviewed or reverted.
compat_fixes() {
  local f
  # tmux >= 3.0: a bare { or } starts a block; *-fg/-bg/-attr became *-style (2.9)
  f="$ETC_DIR/conf/tmux/.tmux.conf"
  if [[ -f $f ]]; then
    sed -i -E \
      -e "s/^([[:space:]]*bind(-key)?([[:space:]]+-[a-zA-Z]+( [^ ]+)?)*[[:space:]]+)([{}])([[:space:]])/\1'\5'\6/" \
      -e 's/^([[:space:]]*)(set|setw|set-option|set-window-option)[[:space:]]+-([a-zA-Z]*)[[:space:]]+([a-z-]+)-(fg|bg)[[:space:]]+([^[:space:]#]+)/\1\2 -\3a \4-style \5=\6/' \
      -e 's/^([[:space:]]*)(set|setw|set-option|set-window-option)[[:space:]]+-([a-zA-Z]*)[[:space:]]+([a-z-]+)-attr[[:space:]]+([^[:space:]#]+)/\1\2 -\3a \4-style \5/' "$f"
  fi
  # polybar >= 3.5 removed internal/volume (same keys in internal/pulseaudio);
  # the update counter only ran if a 2017 server IP answered a ping
  f="$ETC_DIR/conf/polybar/.config/polybar/config"
  if [[ -f $f ]]; then
    sed -i -E -e 's|^type = internal/volume$|type = internal/pulseaudio|' \
      -e 's|^(exec-if = "ping -q -w 2 -c 1 )176\.34\.135\.167( > /dev/null")$|\1archlinux.org\2|' "$f"
  fi
  # i3: a window title matched as an id (i3 rejected the rule)
  sed -i -E 's|^for_window \[id="Open Document"\]|for_window [title="Open Document"]|' "$ETC_DIR"/templates/i3/*.i3 2>/dev/null
  # i3: key names are case-sensitive now (f4 -> F4; those bindings were dead)
  sed -i -E 's/^([[:space:]]*bindsym[[:space:]]+([^[:space:]]+\+)?)f([0-9]{1,2})([[:space:]])/\1F\3\4/' "$ETC_DIR"/templates/i3/*.i3 2>/dev/null
  # ruby >= 2.5 has no -rubygems (rubygems loads by itself)
  [[ -f $ETC_DIR/conf/zsh/.zprofile ]] && sed -i 's/ruby -rubygems -e/ruby -e/g' "$ETC_DIR/conf/zsh/.zprofile"
  # dunst >= 1.7 ignores geometry: add width/origin/offset with the same values
  f="$ETC_DIR/conf/dunst/.config/dunst/dunstrc"
  if [[ -f $f ]] && ! grep -qE '^[[:space:]]*origin[[:space:]]*=' "$f"; then
    local g w xs x ys y origin
    g="$(sed -nE 's/^[[:space:]]*geometry[[:space:]]*=[[:space:]]*"?([^"]*)"?.*/\1/p' "$f" | head -n 1)"
    if [[ $g =~ ^([0-9]+)(x[0-9]+)?([-+])([0-9]+)([-+])([0-9]+)$ ]]; then
      w=${BASH_REMATCH[1]}; xs=${BASH_REMATCH[3]}; x=${BASH_REMATCH[4]}; ys=${BASH_REMATCH[5]}; y=${BASH_REMATCH[6]}
      origin="$([[ $ys == + ]] && echo top || echo bottom)-$([[ $xs == - ]] && echo right || echo left)"
      sed -i -E "s|^([[:space:]]*)geometry[[:space:]]*=.*$|&\n\1width = ${w}\n\1origin = ${origin}\n\1offset = ${x}x${y}|" "$f"
    fi
  fi
  etc_commit "dots.sh: 2017 configs on current versions (tmux 3, polybar 3.7, dunst 1.9, ruby 3, i3 4.2x) - same look"
  [[ -f $MARKER ]] && { local c _; read -r c _ < "$MARKER"; printf '%s %s\n' "$c" "$(git -C "$ETC_DIR" rev-parse HEAD 2>/dev/null)" > "$MARKER"; }
  return 0
}

