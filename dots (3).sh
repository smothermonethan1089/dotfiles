# -----------------------------------------------------------------------------
fetch_release_fonts() {  # fetch_release_fonts <repo> <asset-pattern %s=version> <dir>
  local repo=$1 pattern=$2 dir=$3 tag ver url tmp
  tag="$(git ls-remote --tags --refs "https://github.com/${repo}" 'v*' 2>/dev/null \
         | awk -F/ '{print $3}' | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | sort -V | tail -n 1)"
  [[ -n $tag ]] || return 1
  ver="${tag#v}"
  # shellcheck disable=SC2059
  url="https://github.com/${repo}/releases/download/${tag}/$(printf "$pattern" "$ver")"
  tmp="$(mktemp -d)"
  if curl -fsSL -o "$tmp/f.zip" "$url" && unzip -q -o "$tmp/f.zip" -d "$tmp/x"; then
    mkdir -p "$dir"
    find "$tmp/x" -name '*.ttf' -exec cp -f {} "$dir/" \;
    rm -rf "$tmp"; return 0
  fi
  rm -rf "$tmp"; return 1
}

# Essential PragmataPro (paid) from files you supply: PRAGMATAPRO=<dir|zip>,
# or *PragmataPro*.{ttf,otf,zip} next to dots.sh.
install_pragmatapro() {
  local dest=$1 src f tmp
  local -a found=()
  if [[ -n $PRAGMATAPRO ]]; then
    found=("$PRAGMATAPRO")
  else
    for f in "$SELF_DIR"/*[Pp]ragmata[Pp]ro*.{ttf,otf,zip} "$SELF_DIR"/*[Pp]ragmata[Pp]ro*/; do
      [[ -e $f ]] && found+=("$f")
    done
  fi
  ((${#found[@]})) || {
    font_has 'Essential PragmataPro' || info "Essential PragmataPro not supplied - Iosevka SS08 stands in (see PRAGMATAPRO in --help)"
    return 0
  }
  mkdir -p "$dest"
  for src in "${found[@]}"; do
    if [[ -d $src ]]; then
      find "$src" -type f \( -iname '*.ttf' -o -iname '*.otf' \) -exec cp -f {} "$dest/" \;
    elif [[ $src == *.zip ]]; then
      tmp="$(mktemp -d)"
      unzip -q -o "$src" -d "$tmp" && find "$tmp" -type f \( -iname '*.ttf' -o -iname '*.otf' \) -exec cp -f {} "$dest/" \;
      rm -rf "$tmp"
    elif [[ -f $src ]]; then
      cp -f "$src" "$dest/"
    fi
  done
  fc-cache -f "$dest" >/dev/null 2>&1 || true
  if font_has 'Essential PragmataPro'; then ok "Essential PragmataPro installed (the font in the screenshots)"
  else warn "the PragmataPro files supplied do not contain 'Essential PragmataPro' - check them"; fi
}

