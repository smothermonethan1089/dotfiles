  if have vim; then
    [[ -f ${HOME}/.vim/autoload/plug.vim ]] || curl -fsSLo "${HOME}/.vim/autoload/plug.vim" --create-dirs \
      https://raw.githubusercontent.com/junegunn/vim-plug/master/plug.vim
