# The wallpaper in clean.jpg is not in the repo: rebuild it from the
# screenshot itself (the bar mirrored away, the terminal filled with the star
# field next to it) and hand it to nitrogen, which the repo's .xinitrc restores.
make_wallpaper() {
  if [[ ! -s $WALLPAPER ]]; then
    local src="$CLEAN_JPG" tmp
    tmp="$(mktemp -d)"
    if [[ -z $src ]]; then
      if [[ -f $SELF_DIR/clean.jpg ]]; then src="$SELF_DIR/clean.jpg"
      elif curl -fsSL -o "$tmp/clean.jpg" "$CLEAN_JPG_URL"; then src="$tmp/clean.jpg"; fi
    fi
    if [[ -z $src || ! -f $src ]]; then
      warn "could not get clean.jpg for the wallpaper - put it next to dots.sh (or set CLEAN_JPG) and re-run"
      rm -rf "$tmp"; return 0
    fi
    log "Building the wallpaper from clean.jpg..."
    mkdir -p "$(dirname -- "$WALLPAPER")"
    if have python3 && python3 -c 'import PIL, numpy' 2>/dev/null; then
      python3 -I - "$src" "$WALLPAPER" <<'PY' || warn "wallpaper build failed"
import sys
import numpy as np
from PIL import Image
img = Image.open(sys.argv[1]).convert("RGB")
if img.size != (3840, 2160):                  # coordinates below are for the 4K original
    img = img.resize((3840, 2160), Image.LANCZOS)
im = np.asarray(img).astype(float)
H = im.shape[0]
im[0:34] = im[34:68][::-1]                    # the bar: mirror the sky just below it
x1, y0, dx, f = 1160, 1416, 1300, 140         # terminal box: x < x1, y >= y0; fill from dx to the right
ya, xb = y0 - f, x1 + f                       # plus a feather band above and right of the box
patch = im[ya:H, dx:dx + xb].copy()
base = im[ya:H, 0:xb]
yy = np.arange(ya, H)[:, None]; xx = np.arange(0, xb)[None, :]
a = (np.minimum(np.clip((yy - ya) / f, 0, 1), np.clip((xb - xx) / f, 0, 1)) ** 1.2)[..., None]
im[ya:H, 0:xb] = a * patch + (1 - a) * base
Image.fromarray(im.clip(0, 255).astype("uint8")).save(sys.argv[2], quality=95)
PY
    else
      warn "python-pillow/python-numpy missing - using clean.jpg as it is for the wallpaper"
      cp -f "$src" "$WALLPAPER"
    fi
    rm -rf "$tmp"
  fi
  [[ -s $WALLPAPER ]] || return 0
  mkdir -p "${HOME}/.config/nitrogen"
  printf '[xin_-1]\nfile=%s\nmode=5\nbgcolor=#1c1b19\n' "$WALLPAPER" > "${HOME}/.config/nitrogen/bg-saved.cfg"
  printf '[geometry]\nposx=0\nposy=0\nsizex=800\nsizey=600\n\n[nitrogen]\nview=icon\nrecurse=true\nsort=alpha\nicon_caps=false\ndirs=%s;\n' \
    "$(dirname -- "$WALLPAPER")" > "${HOME}/.config/nitrogen/nitrogen.cfg"
  ok "Wallpaper: ${WALLPAPER/#$HOME/~} (nitrogen --restore in .xinitrc shows it)"
}

# Programs the 2017 setup calls that no longer exist, as small stand-ins in
# ~/bin (each one steps aside when the real program is installed):
#   cower   - ~/utils/pkg.sh (polybar "PKG: x/y") runs 'cower -u' to count AUR updates
#   compton - .xinitrc runs 'compton -b'; picom is compton's successor
