repo_has()      { pacman -Si "$1" >/dev/null 2>&1 || [[ -n "$(pacman -Sg "$1" 2>/dev/null)" ]]; }
pkg_installed() { pacman -Qq "$1" >/dev/null 2>&1; }

has_nvidia_gpu() {
  if [[ -n $INSTALL_NVIDIA ]]; then [[ $INSTALL_NVIDIA == 1 ]]; return; fi
  if have lspci; then lspci 2>/dev/null | grep -iE 'vga|3d|display' | grep -qi nvidia; return; fi
  grep -qs '0x10de' /sys/bus/pci/devices/*/vendor
}

# Sets RESOLVED to the package to install for $1 ("" = skip, reason in SKIP_REASON).
RESOLVED="" SKIP_REASON=""
resolve_pkg() {
  local p=$1 s
  RESOLVED="" SKIP_REASON=""
  for s in $SKIP_PKGS; do
    if [[ $s == "$p" ]]; then SKIP_REASON="listed in SKIP_PKGS"; return 0; fi
  done
  if [[ $NVIDIA_PKGS == *" $p "* ]] && ! has_nvidia_gpu; then
    SKIP_REASON="no NVIDIA GPU found (INSTALL_NVIDIA=1 to install anyway)"; return 0
  fi
  if [[ -v SUBST_PKG[$p] ]]; then
    RESOLVED=${SUBST_PKG[$p]}
    [[ -n $RESOLVED ]] || SKIP_REASON="${SKIP_WHY[$p]:-not installable}"
    return 0
  fi
  RESOLVED=$p
}

install_yay() {
  if have yay; then ok "yay already installed"; return 0; fi
