find_local_zip() {
  if [[ -n $DOTFILES_ZIP ]]; then printf '%s' "$DOTFILES_ZIP"; return 0; fi
  local d f
  for d in "$SELF_DIR" "$PWD"; do
    for f in "$d"/*dotfiles-"${COMMIT}"*.zip "$d"/*dotfiles-"${COMMIT:0:7}"*.zip; do
      if [[ -f $f ]]; then printf '%s' "$f"; return 0; fi
    done
  done
  return 0
}

finish_import() {  # finish_import <description>
  find "$ETC_DIR/scripts" -name '*.sh' -exec chmod +x {} + 2>/dev/null || true
  if [[ ! -d $ETC_DIR/.git ]]; then
    ( cd "$ETC_DIR" && git init -q ) >/dev/null 2>&1
  fi
  etc_commit "Import roosta/dotfiles ${COMMIT} ($1)"
  ok "Dotfiles ${COMMIT:0:7} ready at ${ETC_DIR}"
}

extract_zip() {
  local zip=$1 tmp top
  log "Extracting $(basename -- "$zip") into ${ETC_DIR}"
  tmp="$(mktemp -d)"
  unzip -q "$zip" -d "$tmp" || { rm -rf "$tmp"; die "Could not unzip $zip"; }
  if [[ -f $tmp/Makefile ]]; then top="$tmp"
  else top="$(find "$tmp" -mindepth 1 -maxdepth 1 -type d | head -n 1)"; fi
  if [[ -z $top || ! -f $top/Makefile || ! -d $top/conf ]]; then
    rm -rf "$tmp"; die "$zip does not contain the dotfiles tree (no Makefile/conf)"
  fi
  [[ $(basename -- "$top") == *"$COMMIT"* ]] \
    || warn "$(basename -- "$zip") does not look like commit ${COMMIT:0:7} (top folder: $(basename -- "$top")) - using it anyway"
  mv "$top" "$ETC_DIR" || { rm -rf "$tmp"; die "Could not move the dotfiles to $ETC_DIR"; }
  rm -rf "$tmp"
  finish_import "from $(basename -- "$zip")"
}

clone_commit() {
  log "Cloning ${REPO_URL} at ${COMMIT:0:7}"
  local tmp; tmp="$(mktemp -d)"
  if ! GIT_TERMINAL_PROMPT=0 git clone --quiet --filter=blob:none --no-checkout "$REPO_URL" "$tmp/repo" 2>/dev/null; then
    rm -rf "$tmp/repo"
    GIT_TERMINAL_PROMPT=0 git clone --quiet --no-checkout "$REPO_URL" "$tmp/repo" \
      || { rm -rf "$tmp"; die "Could not clone ${REPO_URL} (offline?). Put dotfiles-${COMMIT}.zip next to dots.sh instead."; }
  fi
  git -C "$tmp/repo" -c advice.detachedHead=false checkout -q "$COMMIT" \
    || { rm -rf "$tmp"; die "Commit ${COMMIT} not found in ${REPO_URL}"; }
  # keep the clone's history: 'git -C ~/etc log' then starts at roosta's commit
  git -C "$tmp/repo" checkout -q -B dots "$COMMIT"
  mv "$tmp/repo" "$ETC_DIR" || { rm -rf "$tmp"; die "Could not move the clone to $ETC_DIR"; }
  rm -rf "$tmp"
  finish_import "git clone"
}

fetch_dotfiles() {
  ((REUSED_ETC)) && return 0
  log "Fetching the dotfiles (${COMMIT:0:7}, ${COMMIT_DATE%%T*})..."
  local zip; zip="$(find_local_zip)"
  if [[ -n $DOTFILES_ZIP && ! -f $DOTFILES_ZIP ]]; then die "DOTFILES_ZIP=${DOTFILES_ZIP} does not exist"; fi
  if [[ -n $zip ]]; then extract_zip "$zip"; else clone_commit; fi
}

