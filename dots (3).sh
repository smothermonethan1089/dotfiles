#
#  Environment overrides:
#    PROFILE=lintilla|garkbit|allitnil   machine profile from local/ (default:
#                                        your hostname if it is one of these,
#                                        otherwise lintilla)
#    SET_HOSTNAME=0        same as --no-hostname. The repo picks the polybar
#                          bars by hostname (scripts/launch-polybar.sh), so
#                          without it there is no bar unless the hostname
#                          already is the profile name.
#    PIN_REPOS=0           same as --latest-repos
#    REWRITE_HOME=0        keep /home/roosta paths in ~/etc as they are
#    SKIP_SPACEMACS=1      leave ~/.emacs.d alone
#    CLEAN_JPG=/path/clean.jpg   screenshot to build the wallpaper from (default:
