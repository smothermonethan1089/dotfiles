# termite as it was in the screenshots: vte-ng 0.50.2-ng + termite of
# 2017-10-28, built from source into ~/.local/opt/termite (Arch dropped it in
# 2021; the AUR package is tried first). Untouched if a termite already works.
build_termite() {
  ((BUILD_TERMITE)) || return 0
  local shim="${HOME}/bin/termite" real prefix="${HOME}/.local/opt/termite"
  real="$(type -aP termite 2>/dev/null | grep -vxF "$shim" | head -n 1)"
  [[ -n $real ]] && return 0
  if [[ -x $prefix/bin/termite ]]; then ln -sfn "$prefix/bin/termite" "$shim"; return 0; fi
  if have yay && yay -S --needed --noconfirm --answerclean None --answerdiff None --answeredit None termite </dev/null >/dev/null 2>&1 \
     && real="$(type -aP termite 2>/dev/null | grep -vxF "$shim" | head -n 1)" && [[ -n $real ]]; then
    ok "termite installed from the AUR"; [[ -f $shim ]] && grep -q 'dots.sh termite shim' "$shim" && rm -f "$shim"
    return 0
  fi
  have g++ && have pkg-config && have autoreconf || { info "termite build needs base-devel - skipped"; return 0; }
  pkg-config --exists gtk+-3.0 libpcre2-8 gnutls 2>/dev/null || { info "termite build needs gtk3, pcre2 and gnutls - skipped"; return 0; }
  log "Building termite from source (vte-ng ${VTE_NG_BRANCH} + termite ${TERMITE_REV:0:7}) - takes a few minutes..."
  local b="${ETC_DIR}/build/termite" logf="${ETC_DIR}/build/termite-build.log"
  local compat='-O2 -fpermissive -Wno-error -include cstdint -include cstdlib -include cstring -include stdexcept'
  rm -rf "$b"; mkdir -p "$b"; : > "$logf"
  (
    set -e
    cd "$b"
    git clone --quiet --depth 1 --branch "$VTE_NG_BRANCH" "$VTE_NG_URL" vte-ng
    cd vte-ng
    NOCONFIGURE=1 ./autogen.sh
    CXXFLAGS="$compat" CFLAGS="-O2 -Wno-error" ./configure --prefix="$prefix" --disable-static \
      --disable-introspection --disable-vala --disable-gtk-doc --disable-silent-rules
    make -j"$(nproc)"
    make install
    cd "$b"
    git clone --quiet "$TERMITE_URL" termite
    cd termite
    git -c advice.detachedHead=false checkout -q "$TERMITE_REV"
    git -c url."https://github.com/".insteadOf=git://github.com/ submodule update --quiet --init
    PKG_CONFIG_PATH="$prefix/lib/pkgconfig:${PKG_CONFIG_PATH:-}" \
      make CXXFLAGS="$compat" LDFLAGS="-Wl,-rpath,$prefix/lib" termite
    install -Dm755 termite "$prefix/bin/termite"
    install -Dm644 termite.desktop "$prefix/share/applications/termite.desktop"
    tic -x -o "${HOME}/.terminfo" termite.terminfo
  ) >>"$logf" 2>&1
  if [[ -x $prefix/bin/termite ]] && "$prefix/bin/termite" --version >/dev/null 2>&1; then
    ln -sfn "$prefix/bin/termite" "$shim"
    mkdir -p "${HOME}/.local/share/applications"
    sed "s|^Exec=termite|Exec=$prefix/bin/termite|" "$prefix/share/applications/termite.desktop" \
      > "${HOME}/.local/share/applications/termite.desktop" 2>/dev/null || true
    cp -f "$logf" "${DOTS_SHARE}/termite-build.log" 2>/dev/null || true
    ok "termite built: ~/bin/termite -> ${prefix/#$HOME/~}/bin/termite"
  else
    mkdir -p "$DOTS_SHARE"; cp -f "$logf" "${DOTS_SHARE}/termite-build.log" 2>/dev/null || true
    warn "termite did not build (log: ~/.local/share/dots/termite-build.log) - the alacritty stand-in is used"
  fi
}

