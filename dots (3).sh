ensure_fonts() {
  have fc-list || return 0
  local fdir="${HOME}/.local/share/fonts"
  if ! font_has 'Iosevka Term'; then
    log "Downloading Iosevka Term (termite, emacs)..."
    fetch_release_fonts be5invis/Iosevka 'PkgTTF-IosevkaTerm-%s.zip' "$fdir/iosevka" \
      || warn "could not download Iosevka Term"
  fi
  if ! font_has 'Iosevka'; then
    log "Downloading Iosevka (i3, polybar, rofi, dunst)..."
    fetch_release_fonts be5invis/Iosevka 'PkgTTF-Iosevka-%s.zip' "$fdir/iosevka" \
      || warn "could not download Iosevka"
  fi
  # Iosevka's PragmataPro-style variant (ss08): the stand-in for Essential PragmataPro
  if ! font_has 'Iosevka SS08'; then
    log "Downloading Iosevka SS08 (PragmataPro style)..."
    fetch_release_fonts be5invis/Iosevka 'PkgTTF-IosevkaSS08-%s.zip' "$fdir/iosevka-ss08" \
      || warn "could not download Iosevka SS08"
  fi
  if ! font_has 'Iosevka Term SS08'; then
    fetch_release_fonts be5invis/Iosevka 'PkgTTF-IosevkaTermSS08-%s.zip' "$fdir/iosevka-ss08" \
      || warn "could not download Iosevka Term SS08"
  fi
  install_pragmatapro "$fdir/pragmatapro"
  if ! font_has 'FiraCode Nerd Font'; then
    fetch_release_fonts ryanoasis/nerd-fonts 'FiraCode.zip' "$fdir/firacode-nerd" \
      || warn "could not install FiraCode Nerd Font (polybar icons)"
  fi

  # polybar asks for fonts by their 2017 names (and for PragmataPro, a paid
  # font roosta owned); map them to today's packages.
  # (A fontconfig alias: the polybar config itself is untouched.)
  mkdir -p "${HOME}/.config/fontconfig/conf.d"
  local pair from to
  {
    echo '<?xml version="1.0"?>'
    echo '<!DOCTYPE fontconfig SYSTEM "fonts.dtd">'
    echo '<!-- Written by dots.sh: 2017 font names used by ~/.config/polybar/config -> current fonts -->'
    echo '<fontconfig>'
    # <accept>: used only when the named font itself is not installed
    # (fontconfig ignores spaces, so this also covers termite's "EssentialPragmataPro Nerd Font")
    for pair in "Fura Code Nerd Font=FiraCode Nerd Font" "FuraCode Nerd Font=FiraCode Nerd Font" \
                "Essential PragmataPro=Iosevka SS08" "Essential PragmataPro Nerd Font=Iosevka Term SS08"; do
      from=${pair%%=*}; to=${pair#*=}
      printf '  <alias binding="same"><family>%s</family><accept><family>%s</family></accept></alias>\n' "$from" "$to"
    done
    echo '</fontconfig>'
  } > "${HOME}/.config/fontconfig/conf.d/50-dots-legacy-font-names.conf"
  fc-cache -f >/dev/null 2>&1 || true
}

