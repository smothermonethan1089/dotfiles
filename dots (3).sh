# roosta's screens on yours: RandR monitors named like his outputs (DP-1,
# DVI-I-1, HDMI-0 for lintilla), so the repo's i3 workspace assignments and
# polybar bars land on your screens unchanged; the main screen renders his
# 3840x2160 desktop scaled to fit (ETC_SCALE=0: your native resolution).
# Runs from /etc/X11/xinit/xinitrc.d, which the repo's .xinitrc sources first.
install_monitor_map() {
  mkdir -p "$DOTS_SHARE"
  cat > "$DOTS_SHARE/monitors.sh" <<'EOF'
#!/bin/sh
# dots.sh: map this machine's screens onto roosta's (see dots.sh --help)
command -v xrandr >/dev/null 2>&1 || exit 0
prof=$(cat "$HOME/.config/dots-profile" 2>/dev/null); [ -n "$prof" ] || prof=lintilla
vars="$HOME/etc/local/$prof/variables.mk"
[ -f "$vars" ] || exit 0
scale=$(cat "$HOME/.config/dots-scale" 2>/dev/null); [ -n "$scale" ] || scale=1
names=$(sed -nE 's/^(primary|secondary|tertiary)_monitor[[:space:]]*=[[:space:]]*"?([^"[:space:]]+)"?.*/\1 \2/p' "$vars" \
        | sort -k1,1 | awk '{o[$1]=$2} END {printf "%s %s %s", o["primary"], o["secondary"], o["tertiary"]}')
q=$(xrandr --query)
prim=$(printf '%s\n' "$q" | awk '/ connected primary/ {print $1; exit}')
[ -n "$prim" ] || prim=$(printf '%s\n' "$q" | awk '/ connected/ {print $1; exit}')
[ -n "$prim" ] || exit 0
others=$(printf '%s\n' "$q" | awk -v p="$prim" '/ connected/ && $1 != p {print $1}')
set -- $names
want1=$1; want2=$2; want3=$3

# main screen: roosta's 3840x2160 desktop, scaled down (or up) to fit
mode=$(printf '%s\n' "$q" | awk -v o="$prim" '$1 == o {f=1; next} f && /^[^ ]/ {exit} f && /\*/ {print $1; exit}')
w=${mode%x*}; h=${mode#*x}
xrandr --output "$prim" --primary --auto
if [ "$scale" = 1 ] && [ -n "$w" ] && [ "$w" != 3840 ]; then
  sh=$(( h * 3840 / w ))
  xrandr --output "$prim" --scale-from "3840x$sh" --filter bilinear 2>/dev/null \
    || xrandr --output "$prim" --scale-from "3840x$sh"
fi
# extra screens: lintilla had DVI-I-1 left of DP-1 and HDMI-0 right of it
i=0
for o in $others; do
  i=$((i + 1))
  if [ $i = 1 ]; then xrandr --output "$o" --auto --left-of "$prim"
  else xrandr --output "$o" --auto --right-of "$prim"; fi
done

alias_mon() {  # alias_mon <roosta's name> <your output>
  [ -n "$1" ] && [ -n "$2" ] || return 0
  [ "$1" = "$2" ] && return 0
  # a real output already has that name: leave it to that output
  printf '%s\n' "$q" | awk '/connected/ {print $1}' | grep -qxF "$1" && return 0
  xrandr --delmonitor "$1" >/dev/null 2>&1
  xrandr --setmonitor "$1" auto "$2" >/dev/null 2>&1
}
alias_mon "$want1" "$prim"
i=1
for o in $others; do
  i=$((i + 1))
  [ $i = 2 ] && alias_mon "$want2" "$o"
  [ $i = 3 ] && alias_mon "$want3" "$o"
done
printf 'Xft.dpi: 192\n*dpi: 192\n' | xrdb -merge 2>/dev/null
exit 0
EOF
  chmod +x "$DOTS_SHARE/monitors.sh"
  printf '%s\n' "$PROFILE" > "${HOME}/.config/dots-profile"
  printf '%s\n' "$ETC_SCALE" > "${HOME}/.config/dots-scale"
  local hook=/etc/X11/xinit/xinitrc.d/95-dots-monitors.sh
  local body='#!/bin/sh
# dots.sh: give this machine'"'"'s screens roosta'"'"'s monitor names and 4K layout
[ -x "$HOME/.local/share/dots/monitors.sh" ] && "$HOME/.local/share/dots/monitors.sh"
'
  if [[ -f $hook ]] && [[ $(cat "$hook") == "${body%$'\n'}" ]]; then return 0; fi
  if have sudo && printf '%s' "$body" | sudo install -Dm755 /dev/stdin "$hook" 2>/dev/null; then
    ok "screens: your outputs get roosta's names and his 4K layout at login (${hook})"
  else
    warn "could not write ${hook} (needs sudo) - run ~/.local/share/dots/monitors.sh after login yourself"
  fi
}

