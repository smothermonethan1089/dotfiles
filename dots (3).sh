# Move ~/<rel> into the backup dir, keeping its path.
backup_paths() {
  local rel dest
  for rel in "$@"; do
    case $rel in ''|/*|*..*) warn "refusing to back up odd path '${rel}'"; continue ;; esac
    [[ -e ${HOME}/${rel} || -L ${HOME}/${rel} ]] || continue
    dest="${BACKUP_DIR}/${rel}"
    mkdir -p "$(dirname -- "$dest")"
    if mv "${HOME}/${rel}" "$dest"; then info "backed up ~/${rel} -> ${dest/#$HOME/~}"
    else warn "could not back up ~/${rel}"; fi
  done
}

# Keep generated/compat files out of 'git status' in ~/etc (stow folds dirs
# into the repo, so tools write there - the repo's .gitignore expects that).
etc_exclude() {
  local f="${ETC_DIR}/.git/info/exclude" p
  [[ -d ${ETC_DIR}/.git ]] || return 0
  mkdir -p "$(dirname -- "$f")"
  for p in "$@"; do grep -qxF "$p" "$f" 2>/dev/null || printf '%s\n' "$p" >> "$f"; done
}

etc_commit() {  # etc_commit <message>
  [[ -d $ETC_DIR/.git ]] || return 0
  (
    cd "$ETC_DIR" && git add -A &&
    { git diff --cached --quiet || git -c user.name="dots.sh" -c user.email="dots.sh@localhost" \
        -c commit.gpgsign=false commit -q -m "$1"; }
  ) >/dev/null 2>&1 || true
}

# -----------------------------------------------------------------------------
# 0. Pre-flight
# -----------------------------------------------------------------------------
preflight() {
  [[ $EUID -ne 0 ]] || die "Run as your normal user (with sudo rights), not as root."

  if ((DO_PACKAGES)); then
    have pacman || die "Installing packages needs Arch Linux (pacman). Use --configs-only to only apply the configs."
    have sudo   || die "sudo is required."
    start_sudo_keepalive
    log "Upgrading the system and installing base tooling (a partial upgrade is unsafe on Arch)..."
    sudo pacman -Syu --needed --noconfirm base-devel git stow unzip curl make \
      || warn "pacman -Syu failed; continuing with what is already installed"
  else
    local -a missing=() t
    for t in git stow unzip curl make; do have "$t" || missing+=("$t"); done
    if ((${#missing[@]})) && have pacman && have sudo; then
      sudo pacman -S --needed --noconfirm "${missing[@]}" || true
    fi
  fi
  local t
  for t in git stow unzip curl make; do have "$t" || die "Required tool missing: $t"; done
  mkdir -p "$BACKUP_DIR"
  ok "Pre-flight checks passed"
}

# -----------------------------------------------------------------------------
# 1. Retire what is installed now
# -----------------------------------------------------------------------------
etc_is_current() {  # ~/etc is this commit, installed by this script
  ((FRESH)) && return 1
  [[ -f $MARKER && -d $ETC_DIR/.git ]] || return 1
  local want _
  read -r want _ < "$MARKER" || return 1
  [[ $want == "$COMMIT" ]]
}

stow_packages_in() {  # stow_packages_in <abs dir>
  [[ -d $1 ]] || return 0
  find "$1" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | sort
}

unstow_tree() {  # remove the links an old ~/etc put into $HOME
  local root=$1 dir
  local -a pkgs=()
  for dir in "$root/conf" "$root"/local/*/conf; do
    [[ -d $dir ]] || continue
    mapfile -t pkgs < <(stow_packages_in "$dir")
    ((${#pkgs[@]})) || continue
    stow -D -t "$HOME" -d "$dir" "${pkgs[@]}" >/dev/null 2>&1 \
      || stow -D --no-folding -t "$HOME" -d "$dir" "${pkgs[@]}" >/dev/null 2>&1 || true
  done
}

# Links into ~/etc whose target no longer exists (left by older installs).
remove_dangling_etc_links() {
  local l t n=0
  while IFS= read -r -d '' l; do
    t="$(readlink -- "$l")"
    case $t in
      *etc/conf/*|*etc/local/*|*etc/scripts/*|"$ETC_DIR"/*) rm -f -- "$l"; n=$((n + 1)) ;;
    esac
  done < <(find "$HOME" -maxdepth 6 \
             \( -path "$ETC_DIR" -o -path "$HOME/backup" -o -path "$HOME/.cache" -o -path "$HOME/src" \
                -o -path "$HOME/lib" -o -path "$HOME/.local/share/Steam" -o -path "$HOME/.cargo" \
                -o -path "$HOME/.rustup" -o -path "$HOME/.npm" -o -path "$HOME/node_modules" \) -prune \
             -o -xtype l -print0 2>/dev/null)
  ((n)) && info "removed ${n} dangling links into the old ~/etc"
  return 0
}

# A newer roosta/dotfiles install (main branch: Hyprland/Quickshell/Kando, a
# bare repo in ~/.dotfiles checked out into $HOME - e.g. by the main-branch
# dots.sh): move every file it checked out, its submodules and the repo itself
# to the backup, plus the desktop-click helpers that dots.sh added for it.
retire_main_checkout() {
  local bare="${HOME}/.dotfiles" p n=0
  [[ -f $bare/HEAD ]] && [[ $(git --git-dir="$bare" config --get core.bare 2>/dev/null) == true ]] || return 0
  git --git-dir="$bare" config --get remote.origin.url 2>/dev/null | grep -qi 'roosta/dotfiles' \
    || git --git-dir="$bare" log -1 --format=%s 2>/dev/null | grep -qi 'roosta/dotfiles' || return 0
  log "Retiring the newer roosta/dotfiles install (bare repo ~/.dotfiles, Hyprland)..."
  while IFS= read -r -d '' p; do
    [[ -e $HOME/$p || -L $HOME/$p ]] || continue
    backup_paths "$p"; n=$((n + 1))
  done < <(git --git-dir="$bare" --work-tree="$HOME" ls-files -z 2>/dev/null)
  local rel
  for rel in .config/hypr/monitors/current.lua .config/autostart/dots-desktop-clicks.desktop \
             .config/autostart/kando.desktop .local/share/dots/desktop-clicks; do
    if [[ -e $HOME/$rel || -L $HOME/$rel ]]; then
      case $rel in
        *autostart*) grep -qs 'dots.sh' "$HOME/$rel" && backup_paths "$rel" ;;
        *) backup_paths "$rel" ;;
      esac
    fi
  done
  backup_paths .dotfiles
  # empty folders the checkout leaves behind (only ones that hold nothing at all)
  for rel in .config/hypr .config/quickshell .config/kando .config/uwsm .config/srcery .zsh.d scripts; do
    [[ -d $HOME/$rel ]] && find "$HOME/$rel" -depth -type d -empty -delete 2>/dev/null
  done
  ok "Newer install retired (${n} files/folders moved to the backup)"
}

retire_previous() {
  log "Replacing the current setup (everything moved goes to ${BACKUP_DIR/#$HOME/~})..."
  retire_main_checkout
  if [[ -e $ETC_DIR ]] && etc_is_current; then
    REUSED_ETC=1
    local changed
    changed="$(git -C "$ETC_DIR" status --porcelain --untracked-files=no 2>/dev/null | wc -l)"
    ok "~/etc already is ${COMMIT:0:7} (installed by dots.sh) - keeping it"
    ((changed)) && info "${changed} files in ~/etc differ from the commit (your edits, kept; FRESH=1 starts over: git -C ~/etc status)"
    return 0
  fi

  if [[ -d $ETC_DIR/conf ]]; then
    info "unstowing the old ~/etc"
    unstow_tree "$ETC_DIR"
  fi
  if [[ -e $ETC_DIR || -L $ETC_DIR ]]; then
    backup_paths etc
  fi

  # Files an earlier dots.sh generated or wrote outside ~/etc
  local rel
  for rel in .i3/config .config/rofi/config .config/rofi/config.rasi .config/dunst/dunstrc; do
    [[ -f $HOME/$rel && ! -L $HOME/$rel ]] && backup_paths "$rel"
  done
  for rel in .xprofile .i3/monitors.conf .config/etc-profile .config/etc-dpi \
             .config/mopidy/mopidy.conf .config/systemd/user/startpage.service; do
    [[ -f $HOME/$rel ]] || continue
    if [[ $rel == .config/etc-* ]] || grep -qE 'dots\.sh|etc-monitors|Start page for Firefox' "$HOME/$rel" 2>/dev/null; then
      if [[ $rel == *startpage.service ]] && have systemctl; then
        systemctl --user disable --now startpage.service >/dev/null 2>&1 || true
      fi
      backup_paths "$rel"
    fi
  done
  # links an earlier dots.sh (2019 commit) made that the 2017 setup does not have
  local l
  for l in scripts bin/tmain bin/tmusic bin/tssh bin/rxtx bin/loadavg bin/vidir bin/bakc; do
    [[ -L $HOME/$l ]] && rm -f -- "${HOME:?}/$l"
  done
  # old dots.sh linked scripts from a 'deprecated' checkout into ~/src/scripts
  if [[ -d $HOME/src/scripts ]]; then
    find "$HOME/src/scripts" -maxdepth 1 -type l -lname '*scripts-deprecated*' -delete 2>/dev/null || true
  fi
  remove_dangling_etc_links
  ok "Old setup retired"
}

