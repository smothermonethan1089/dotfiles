# -----------------------------------------------------------------------------
# 6. Repositories in ~/lib, ~/src and ~/.zsh.d/plugins
# -----------------------------------------------------------------------------
default_branch() {  # default_branch <repo dir>  -> origin/<branch>
  local d=$1 b
  b="$(git -C "$d" symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null)"
  if [[ -z $b ]]; then
    git -C "$d" remote set-head origin -a >/dev/null 2>&1
    b="$(git -C "$d" symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null)"
  fi
  printf '%s' "${b:-origin/master}"
}

sync_repo() {  # sync_repo <url> <parent> [dirname]
  local url=$1 parent=$2 name=${3:-}
  if [[ -z $name ]]; then name="${url##*/}"; name="${name%.git}"; fi
  local dest="${parent}/${name}"

  if [[ -d $dest/.git ]]; then
    [[ -f $dest/.git/shallow ]] && git -C "$dest" fetch --quiet --unshallow 2>/dev/null
    git -C "$dest" fetch --quiet origin 2>/dev/null || info "could not fetch ${name} (offline?)"
  elif [[ -e $dest ]]; then
    warn "${dest/#$HOME/~} exists and is not a git checkout - skipped"; return 0
  else
    mkdir -p "$parent"
    if ! GIT_TERMINAL_PROMPT=0 git clone --quiet --filter=blob:none "$url" "$dest" 2>/dev/null; then
      rm -rf "$dest"
      GIT_TERMINAL_PROMPT=0 git clone --quiet "$url" "$dest" || { warn "could not clone ${url}"; return 0; }
    fi
  fi

  if [[ -n "$(git -C "$dest" status --porcelain --untracked-files=no 2>/dev/null)" ]]; then
    info "kept ${dest/#$HOME/~} as it is (local changes)"; return 0
  fi
  local base rev
  base="$(default_branch "$dest")"
  if ((PIN_REPOS)); then
    rev="$(git -C "$dest" rev-list -n 1 --before="$COMMIT_DATE" "$base" 2>/dev/null)"
    if [[ -n $rev ]]; then
      git -C "$dest" -c advice.detachedHead=false checkout -q --detach "$rev" 2>/dev/null \
        && { info "${name} @ ${rev:0:7} (as on ${COMMIT_DATE%%T*})"; return 0; }
      warn "could not check out ${name} at ${rev:0:7}"; return 0
    fi
    info "${name}: no commit before ${COMMIT_DATE%%T*}, using the newest"
  fi
  local br=${base#origin/}
  git -C "$dest" checkout -q "$br" 2>/dev/null || git -C "$dest" checkout -q -b "$br" "$base" 2>/dev/null
  git -C "$dest" merge --ff-only --quiet "$base" 2>/dev/null && info "${name} @ newest" \
    || info "kept ${name} where it is"
}

sync_list() {  # sync_list <parent> <listfile>   (git@github.com: -> https, no SSH key needed)
  local parent=$1 list=$2 url
  mkdir -p "$parent"
  while IFS= read -r url; do
    url="${url/#git@github.com:/https://github.com/}"
    sync_repo "$url" "$parent"
  done < <(read_list "$list")
}

