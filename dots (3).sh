#  https://github.com/roosta/dotfiles/tree/c65e38be2956e153dbb229bc1035ded86dfd6d9d
#
#  The 2017 desktop: i3 + polybar, termite, rofi, dunst, compton, zsh + pure,
#  tmux, vim, spacemacs, ranger, ncmpcpp/mopidy, srcery colours (vim-srcery).
#
#  What it does:
#    * REPLACES what is installed now: an existing ~/etc (including one set up
#      by an earlier dots.sh) is unstowed and moved to ~/backup/..., a newer
#      roosta/dotfiles install (bare repo ~/.dotfiles, Hyprland) is moved there
#      too, and every file in $HOME that is in the way of the repo's configs.
#    * Uses ALL configs from that commit, unmodified: every package in conf/ is
#      stowed the way the repo's Makefile does it (only *.md / *.org ignored,
#      so firefox is included), plus local/<profile>/conf. i3, rofi and dunst
#      are generated by the repo's own Makefile rules.
#    * The repos the configs load from ~/src, ~/lib, ~/.zsh.d/plugins
#      (scripts, srcery-terminal, srcery-vim, pure, ...) are checked out as they
#      were on the commit date (2017-11-03), so they match the configs - and
#      so is spacemacs in ~/.emacs.d (the Makefile's init-spacemacs rule).
#
#  Changes inside ~/etc: /home/roosta -> your $HOME (the repo hardcodes it)
#  and the 2017 -> today fixes below, each a separate git commit. Everything else needed on a 2020s Arch (termite shim, legacy
#  font names, rofi .rasi) is added OUTSIDE ~/etc and leaves the repo's files
#  as they are. 'git -C ~/etc log' shows the one change.
#
#  From the screenshots (not in the repo):
#    * the cloud wallpaper (clean.jpg with the bar and terminal removed)
#    * the pink archey3 logo (clean.jpg)                     -> archey3
#    * the green "ETC" logo, rebuilt cell by cell from busy.png -> etc-logo
#    * the busy.png tmux session: logo + vtop | vim + cava | ncmpcpp -> etc-busy
#    * termite itself, built from source (vte-ng 0.50 + termite of Oct 2017)
#    * your screens get roosta's monitor names (DP-1, DVI-I-1, HDMI-0) and the
#      main one renders his 3840x2160 desktop, scaled to fit - so i3, polybar
#      and rofi lay out exactly as in the pictures on any 16:9 screen
#  Mouse: right-click the desktop for a menu of everything the keyboard
#  bindings do (terminal, rofi, workspaces, lock/logout/...); right-click a
#  window's title bar for a window menu (close, float, fullscreen, move to...).
#
#  2017 -> today fixes, committed in ~/etc as "dots.sh: 2017 configs on current
#  versions" (git -C ~/etc show / revert): tmux 3 syntax, polybar's removed
#  volume module, dunst's removed geometry, ruby -rubygems, a broken i3 rule.
#  Same look, no errors.
#
#  Fonts: the bar, rofi, i3 titles and termite use Essential PragmataPro, a
#  paid font that cannot be downloaded. Put your PragmataPro .ttf/.otf files
#  (or a zip of them) next to dots.sh, or set PRAGMATAPRO=<dir|zip>, and they
#  are installed. Without them, Iosevka SS08 - Iosevka's PragmataPro-style
#  variant - stands in.
#
#  Source of the dotfiles (first match wins):
#    1. ~/etc, if it already is this commit installed by this script
#    2. a zip of this commit next to this script or in $PWD
#       (*dotfiles-c65e38be2956e153dbb229bc1035ded86dfd6d9d*.zip), or $DOTFILES_ZIP
#    3. git clone of $REPO_URL at $COMMIT
#
#  Usage:  bash dots.sh [--configs-only] [--skip-packages] [--skip-plugins]
#                       [--skip-services] [--no-hostname] [--latest-repos]
#                       [-h|--help]
#
#    --configs-only   only (re)apply configs: no packages, plugins or services
#    --no-hostname    do not rename the machine to the profile name
#    --latest-repos   use the newest ~/src ~/lib and zsh plugin repos instead of
