# rofi >= 1.7 only reads config.rasi. Translate the generated ~/.config/rofi/config
# key by key; keys this rofi no longer knows are left out (and listed).
rofi_config_to_rasi() {
  local src="${HOME}/.config/rofi/config" dst="${HOME}/.config/rofi/config.rasi" dump dropped
  [[ -f $src ]] || return 0
  have rofi || { info "rofi not installed - config.rasi not written"; return 0; }
  dump="$(rofi -dump-config 2>/dev/null)"
  # no X (e.g. run from the installer's chroot): use a virtual X server
  [[ -z $dump ]] && have xvfb-run && dump="$(xvfb-run -a rofi -dump-config 2>/dev/null)"
  if [[ -z $dump ]]; then
    info "rofi -dump-config needs a running X session; config.rasi is written on the next run from X"
    return 0
  fi
  dropped="$(mktemp)"
  {
    echo "/* Written by dots.sh from ~/.config/rofi/config (generated by 'make rofi'"
    echo "   from ~/etc/templates/rofi/config.rofi) - rofi 1.7 reads only this format. */"
    awk -v dropped="$dropped" -v uid="$(id -u)" '
      NR == FNR {                                   # rofi -dump-config: key -> type
        if (match($0, /^[[:space:]]*(\/\*)?[[:space:]]*[a-z0-9-]+:/)) {
          line = $0; sub(/^[[:space:]]*(\/\*)?[[:space:]]*/, "", line)
          k = line; sub(/:.*/, "", k)
          v = line; sub(/^[^:]*:[[:space:]]*/, "", v); sub(/;?[[:space:]]*(\*\/)?[[:space:]]*$/, "", v)
          if (v ~ /^"/) t = "s"; else if (v ~ /^(true|false)$/) t = "b"; else if (v ~ /^-?[0-9]+$/) t = "i"; else t = "s"
          type[k] = t
        }
        next
      }
      /^[[:space:]]*!/ || !/^[[:space:]]*rofi\./ { next }
      {
        line = $0; sub(/^[[:space:]]*rofi\./, "", line)
        k = line; sub(/:.*/, "", k)
        v = line; sub(/^[^:]*:/, "", v); gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
        if (v ~ /^".*"$/) v = substr(v, 2, length(v) - 2)
        if (k == "pid") sub(/^\/run\/user\/[0-9]+\//, "/run/user/" uid "/", v)   # was uid 1000
        if (v == "") next
        if (k == "theme") { theme = v; next }
        if (!(k in type)) {
          if (k == "modi" && ("modes" in type)) k = "modes"
          else if (k == "combi-modi" && ("combi-modes" in type)) k = "combi-modes"
        }
        if (!(k in type)) {
          # layout options rofi 1.7 moved into the theme
          if (k == "width" && v ~ /^[0-9]+$/) { lay = lay sprintf("window { width: %s; }\n", (v + 0 <= 100 ? v "%" : v "px")); next }
          if (k == "lines" && v ~ /^[0-9]+$/) { lines = v; next }
          if (k == "columns" && v ~ /^[0-9]+$/) { cols = v; next }
          if (k == "fullscreen" && v == "true") { lay = lay "window { fullscreen: true; }\n"; next }
          print k > dropped; next
        }
        t = type[k]
        if (t == "b" && v !~ /^(true|false)$/) t = "s"
        if (t == "i" && v !~ /^-?[0-9]+$/) t = "s"
        if (t == "s") { gsub(/\\/, "\\\\", v); gsub(/"/, "\\\"", v); v = "\"" v "\"" }
        val[k] = v; if (!(k in seen)) { order[++n] = k; seen[k] = 1 }   # last one wins, like xrdb
      }
      END {
        print "configuration {"
        for (i = 1; i <= n; i++) printf "  %s: %s;\n", order[i], val[order[i]]
        print "}"
        if (theme != "") printf "@theme \"%s\"\n", theme
        if (lines != "" || cols != "") {
          lay = lay "listview {"
          if (lines != "") lay = lay sprintf(" lines: %s;", lines)
          if (cols != "") lay = lay sprintf(" columns: %s;", cols)
          lay = lay " }\n"
        }
        if (lay != "") { print "/* width / lines / columns from the old config, now theme properties */"; printf "%s", lay }
      }
    ' <(printf '%s\n' "$dump") "$src"
  } > "$dst.tmp" && mv -f "$dst.tmp" "$dst"
  if [[ -s $dropped ]]; then
    info "rofi: left out options removed in rofi $(rofi -v 2>/dev/null | awk '{print $2}'): $(sort -u "$dropped" | tr '\n' ' ')"
  fi
  rm -f "$dropped"
  etc_exclude "conf/rofi/.config/rofi/config.rasi"
  ok "rofi: ~/.config/rofi/config.rasi"
}

